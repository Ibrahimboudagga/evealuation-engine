from typing import Any, Dict, Optional
from pydantic import BaseModel, Field, field_validator

from app.schemas.outcomes import EvaluationOutcome

class EvaluationResult(BaseModel):
    example_id: str = Field(..., description="ID of the evaluation example")
    prompt: str = Field(..., description="The prompt or input text provided to the model")
    prediction: str = Field(..., description="The predicted output generated by the model")
    expected_output: str = Field(..., description="The ground truth or expected output")
    score: Optional[float] = Field(default=None, description="The evaluation score, or null when evaluation did not complete")
    evaluator_name: str = Field(..., description="Name of the evaluator used")
    outcome: EvaluationOutcome = Field(default=EvaluationOutcome.EVALUATED, description="Whether scoring completed or failed")
    error_message: Optional[str] = Field(default=None, description="Sanitized error when scoring did not complete")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Optional metadata (e.g. latency, token count, reasoning, etc.)")
    prompt_tokens: Optional[int] = Field(default=None, description="Number of prompt tokens used by the provider")
    completion_tokens: Optional[int] = Field(default=None, description="Number of completion tokens generated by the provider")

    @field_validator("score", mode="before")
    @classmethod
    def normalized_quality_score(cls, value):
        # Local import avoids a schema/database import cycle.
        from app.services.result_integrity import is_valid_quality_score
        if value is not None and not is_valid_quality_score(value):
            raise ValueError("Score must be a finite number between zero and one, not a boolean or string.")
        return value
